export function ambientTrackIcon(item, size = 14) {
  const rawName = String(item?.name || '').toLowerCase();
  const baseId = rawName.split('/').pop()?.replace(/\.[a-z0-9]+$/i, '') || '';
  const shapeKey = SOUND_SHAPES[baseId]
    ? baseId
    : (CATEGORY_FALLBACK[item?.category] || 'white-noise');
  const nodes = SOUND_SHAPES[shapeKey]();
  return h('svg', {
    viewBox: '0 0 20 20',
    width: size,
    height: size,
    fill: 'none',
    stroke: 'currentColor',
    strokeWidth: 1.55,
    strokeLinecap: 'round',
    strokeLinejoin: 'round',
    'aria-hidden': true,
    style: { flex: '0 0 auto' },
  }, ...nodes);
}
